-- Crea las 11 tablas con PK identity, FK, UNIQUE, NOT NULL y valores por defecto.
CREATE TABLE ROL (
  ID_ROL         NUMBER(10) GENERATED ALWAYS AS IDENTITY,
  NOMBRE         VARCHAR2(30 CHAR)  NOT NULL,
  DESCRIPCION    VARCHAR2(200 CHAR),
  DIAS_PRESTAMO  NUMBER(3)          NOT NULL,
  MAX_PRESTAMOS  NUMBER(2)          NOT NULL,
  CONSTRAINT PK_ROL PRIMARY KEY (ID_ROL),
  CONSTRAINT UK_ROL_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE USUARIO (
  ID_USUARIO      NUMBER(10) GENERATED ALWAYS AS IDENTITY,
  CODIGO          VARCHAR2(20 CHAR)  NOT NULL,
  NOMBRES         VARCHAR2(100 CHAR) NOT NULL,
  APELLIDOS       VARCHAR2(100 CHAR) NOT NULL,
  CORREO          VARCHAR2(150 CHAR) NOT NULL,
  TELEFONO        VARCHAR2(20 CHAR),
  DIRECCION       VARCHAR2(250 CHAR),
  FECHA_REGISTRO  DATE DEFAULT CURRENT_DATE NOT NULL,
  ESTADO          CHAR(1) DEFAULT 'A' NOT NULL,
  ID_ROL          NUMBER(10)         NOT NULL,
  USERNAME        VARCHAR2(50 CHAR)  NOT NULL,
  PASSWORD_HASH   VARCHAR2(100 CHAR) NOT NULL,
  CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
  CONSTRAINT UK_USUARIO_CODIGO UNIQUE (CODIGO),
  CONSTRAINT UK_USUARIO_CORREO UNIQUE (CORREO),
  CONSTRAINT UK_USUARIO_USERNAME UNIQUE (USERNAME),
  CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (ID_ROL) REFERENCES ROL (ID_ROL)
);

CREATE TABLE AUTOR (
  ID_AUTOR      NUMBER(10) GENERATED ALWAYS AS IDENTITY,
  NOMBRES       VARCHAR2(100 CHAR) NOT NULL,
  APELLIDOS     VARCHAR2(100 CHAR) NOT NULL,
  NACIONALIDAD  VARCHAR2(60 CHAR),
  CONSTRAINT PK_AUTOR PRIMARY KEY (ID_AUTOR)
);

CREATE TABLE EDITORIAL (
  ID_EDITORIAL  NUMBER(10) GENERATED ALWAYS AS IDENTITY,
  NOMBRE        VARCHAR2(150 CHAR) NOT NULL,
  PAIS          VARCHAR2(60 CHAR),
  CONSTRAINT PK_EDITORIAL PRIMARY KEY (ID_EDITORIAL),
  CONSTRAINT UK_EDITORIAL_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE CATEGORIA (
  ID_CATEGORIA  NUMBER(10) GENERATED ALWAYS AS IDENTITY,
  NOMBRE        VARCHAR2(100 CHAR) NOT NULL,
  DESCRIPCION   VARCHAR2(250 CHAR),
  CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID_CATEGORIA),
  CONSTRAINT UK_CATEGORIA_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE LIBRO (
  ID_LIBRO          NUMBER(10) GENERATED ALWAYS AS IDENTITY,
  ISBN              VARCHAR2(20 CHAR)  NOT NULL,
  TITULO            VARCHAR2(250 CHAR) NOT NULL,
  ANIO_PUBLICACION  NUMBER(4),
  EDICION           VARCHAR2(30 CHAR),
  IDIOMA            VARCHAR2(30 CHAR),
  NUM_PAGINAS       NUMBER(5),
  ID_EDITORIAL      NUMBER(10)         NOT NULL,
  ID_CATEGORIA      NUMBER(10)         NOT NULL,
  ESTADO            CHAR(1) DEFAULT 'A' NOT NULL,
  CONSTRAINT PK_LIBRO PRIMARY KEY (ID_LIBRO),
  CONSTRAINT UK_LIBRO_ISBN UNIQUE (ISBN),
  CONSTRAINT FK_LIBRO_EDITORIAL FOREIGN KEY (ID_EDITORIAL) REFERENCES EDITORIAL (ID_EDITORIAL),
  CONSTRAINT FK_LIBRO_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA (ID_CATEGORIA)
);

CREATE TABLE LIBRO_AUTOR (
  ID_LIBRO  NUMBER(10) NOT NULL,
  ID_AUTOR  NUMBER(10) NOT NULL,
  CONSTRAINT PK_LIBRO_AUTOR PRIMARY KEY (ID_LIBRO, ID_AUTOR),
  CONSTRAINT FK_LIBRO_AUTOR_LIBRO FOREIGN KEY (ID_LIBRO) REFERENCES LIBRO (ID_LIBRO),
  CONSTRAINT FK_LIBRO_AUTOR_AUTOR FOREIGN KEY (ID_AUTOR) REFERENCES AUTOR (ID_AUTOR)
);

CREATE TABLE EJEMPLAR (
  ID_EJEMPLAR        NUMBER(10) GENERATED ALWAYS AS IDENTITY,
  ID_LIBRO           NUMBER(10)        NOT NULL,
  CODIGO_BARRAS      VARCHAR2(30 CHAR) NOT NULL,
  ESTADO             VARCHAR2(15 CHAR) DEFAULT 'DISPONIBLE' NOT NULL,
  FECHA_ADQUISICION  DATE DEFAULT CURRENT_DATE NOT NULL,
  CONSTRAINT PK_EJEMPLAR PRIMARY KEY (ID_EJEMPLAR),
  CONSTRAINT UK_EJEMPLAR_CODIGO_BARRAS UNIQUE (CODIGO_BARRAS),
  CONSTRAINT FK_EJEMPLAR_LIBRO FOREIGN KEY (ID_LIBRO) REFERENCES LIBRO (ID_LIBRO)
);

CREATE TABLE PRESTAMO (
  ID_PRESTAMO                NUMBER(10) GENERATED ALWAYS AS IDENTITY,
  ID_USUARIO                 NUMBER(10) NOT NULL,
  ID_EJEMPLAR                NUMBER(10) NOT NULL,
  ID_BIBLIOTECARIO           NUMBER(10) NOT NULL,
  FECHA_PRESTAMO             DATE DEFAULT CURRENT_DATE NOT NULL,
  FECHA_DEVOLUCION_PREVISTA  DATE       NOT NULL,
  ESTADO                     VARCHAR2(10 CHAR) DEFAULT 'ACTIVO' NOT NULL,
  CONSTRAINT PK_PRESTAMO PRIMARY KEY (ID_PRESTAMO),
  CONSTRAINT FK_PRESTAMO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
  CONSTRAINT FK_PRESTAMO_EJEMPLAR FOREIGN KEY (ID_EJEMPLAR) REFERENCES EJEMPLAR (ID_EJEMPLAR),
  CONSTRAINT FK_PRESTAMO_BIBLIOTECARIO FOREIGN KEY (ID_BIBLIOTECARIO) REFERENCES USUARIO (ID_USUARIO)
);

CREATE TABLE DEVOLUCION (
  ID_DEVOLUCION          NUMBER(10) GENERATED ALWAYS AS IDENTITY,
  ID_PRESTAMO            NUMBER(10) NOT NULL,
  FECHA_DEVOLUCION_REAL  DATE DEFAULT CURRENT_DATE NOT NULL,
  A_TIEMPO               CHAR(1)    NOT NULL,
  DIAS_RETRASO           NUMBER(4) DEFAULT 0 NOT NULL,
  OBSERVACIONES          VARCHAR2(500 CHAR),
  ID_BIBLIOTECARIO       NUMBER(10) NOT NULL,
  CONSTRAINT PK_DEVOLUCION PRIMARY KEY (ID_DEVOLUCION),
  CONSTRAINT UK_DEVOLUCION_PRESTAMO UNIQUE (ID_PRESTAMO),
  CONSTRAINT FK_DEVOLUCION_PRESTAMO FOREIGN KEY (ID_PRESTAMO) REFERENCES PRESTAMO (ID_PRESTAMO),
  CONSTRAINT FK_DEVOLUCION_BIBLIOTECARIO FOREIGN KEY (ID_BIBLIOTECARIO) REFERENCES USUARIO (ID_USUARIO)
);

CREATE TABLE BITACORA (
  ID_BITACORA       NUMBER(10) GENERATED ALWAYS AS IDENTITY,
  FECHA_HORA        TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
  USUARIO           VARCHAR2(128 CHAR) NOT NULL,
  TABLA             VARCHAR2(30 CHAR)  NOT NULL,
  OPERACION         VARCHAR2(6 CHAR)   NOT NULL,
  ID_REGISTRO       NUMBER(10),
  DATOS_ANTERIORES  CLOB,
  DATOS_NUEVOS      CLOB,
  CONSTRAINT PK_BITACORA PRIMARY KEY (ID_BITACORA)
);
