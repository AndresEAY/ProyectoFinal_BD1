-- Bitácora (RN9): procedimiento de registro y triggers AFTER INSERT/UPDATE/DELETE en las tablas críticas.
-- El usuario es el CLIENT_IDENTIFIER fijado por la aplicación o, si no hay, el usuario de la sesión.
CREATE OR REPLACE PROCEDURE SP_REGISTRAR_BITACORA (
  p_tabla             IN VARCHAR2,
  p_operacion         IN VARCHAR2,
  p_id_registro       IN NUMBER,
  p_datos_anteriores  IN CLOB,
  p_datos_nuevos      IN CLOB
) AS
BEGIN
  INSERT INTO BITACORA (FECHA_HORA, USUARIO, TABLA, OPERACION, ID_REGISTRO, DATOS_ANTERIORES, DATOS_NUEVOS)
  VALUES (
    LOCALTIMESTAMP,
    COALESCE(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), SYS_CONTEXT('USERENV', 'SESSION_USER')),
    p_tabla, p_operacion, p_id_registro, p_datos_anteriores, p_datos_nuevos
  );
END;
/

CREATE OR REPLACE TRIGGER TRG_USUARIO_BITACORA
AFTER INSERT OR UPDATE OR DELETE ON USUARIO
FOR EACH ROW
DECLARE
  v_anteriores CLOB;
  v_nuevos     CLOB;
BEGIN
  IF UPDATING OR DELETING THEN
    SELECT JSON_OBJECT('ID_USUARIO' VALUE :OLD.ID_USUARIO, 'CODIGO' VALUE :OLD.CODIGO, 'NOMBRES' VALUE :OLD.NOMBRES, 'APELLIDOS' VALUE :OLD.APELLIDOS, 'CORREO' VALUE :OLD.CORREO, 'TELEFONO' VALUE :OLD.TELEFONO, 'DIRECCION' VALUE :OLD.DIRECCION, 'FECHA_REGISTRO' VALUE :OLD.FECHA_REGISTRO, 'ESTADO' VALUE :OLD.ESTADO, 'ID_ROL' VALUE :OLD.ID_ROL, 'USERNAME' VALUE :OLD.USERNAME) INTO v_anteriores FROM dual;
  END IF;
  IF INSERTING OR UPDATING THEN
    SELECT JSON_OBJECT('ID_USUARIO' VALUE :NEW.ID_USUARIO, 'CODIGO' VALUE :NEW.CODIGO, 'NOMBRES' VALUE :NEW.NOMBRES, 'APELLIDOS' VALUE :NEW.APELLIDOS, 'CORREO' VALUE :NEW.CORREO, 'TELEFONO' VALUE :NEW.TELEFONO, 'DIRECCION' VALUE :NEW.DIRECCION, 'FECHA_REGISTRO' VALUE :NEW.FECHA_REGISTRO, 'ESTADO' VALUE :NEW.ESTADO, 'ID_ROL' VALUE :NEW.ID_ROL, 'USERNAME' VALUE :NEW.USERNAME) INTO v_nuevos FROM dual;
  END IF;
  SP_REGISTRAR_BITACORA(
    'USUARIO',
    CASE WHEN INSERTING THEN 'INSERT' WHEN UPDATING THEN 'UPDATE' ELSE 'DELETE' END,
    NVL(:NEW.ID_USUARIO, :OLD.ID_USUARIO),
    v_anteriores,
    v_nuevos
  );
END;
/

