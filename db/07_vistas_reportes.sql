-- Vistas de reportes y resúmenes (Fase 7).
CREATE OR REPLACE VIEW VW_LIBROS_MAS_PRESTADOS AS
SELECT l.ID_LIBRO, l.ISBN, l.TITULO, c.NOMBRE AS CATEGORIA, COUNT(p.ID_PRESTAMO) AS TOTAL_PRESTAMOS
FROM LIBRO l
JOIN CATEGORIA c ON c.ID_CATEGORIA = l.ID_CATEGORIA
JOIN EJEMPLAR e ON e.ID_LIBRO = l.ID_LIBRO
JOIN PRESTAMO p ON p.ID_EJEMPLAR = e.ID_EJEMPLAR
GROUP BY l.ID_LIBRO, l.ISBN, l.TITULO, c.NOMBRE;

CREATE OR REPLACE VIEW VW_PRESTAMOS_ACTIVOS AS
SELECT p.ID_PRESTAMO, p.ID_USUARIO, u.CODIGO, u.NOMBRES || ' ' || u.APELLIDOS AS USUARIO, r.NOMBRE AS ROL,
       e.CODIGO_BARRAS, l.TITULO, p.FECHA_PRESTAMO, p.FECHA_DEVOLUCION_PREVISTA, p.ESTADO,
       p.FECHA_DEVOLUCION_PREVISTA - TRUNC(CURRENT_DATE) AS DIAS_RESTANTES
FROM PRESTAMO p
JOIN USUARIO u ON u.ID_USUARIO = p.ID_USUARIO
JOIN ROL r ON r.ID_ROL = u.ID_ROL
JOIN EJEMPLAR e ON e.ID_EJEMPLAR = p.ID_EJEMPLAR
JOIN LIBRO l ON l.ID_LIBRO = e.ID_LIBRO
WHERE p.ESTADO IN ('ACTIVO', 'VENCIDO');

CREATE OR REPLACE VIEW VW_PRESTAMOS_VENCIDOS AS
SELECT p.ID_PRESTAMO, u.CODIGO, u.NOMBRES || ' ' || u.APELLIDOS AS USUARIO, u.CORREO,
       e.CODIGO_BARRAS, l.TITULO, p.FECHA_PRESTAMO, p.FECHA_DEVOLUCION_PREVISTA,
       TRUNC(CURRENT_DATE) - p.FECHA_DEVOLUCION_PREVISTA AS DIAS_RETRASO
FROM PRESTAMO p
JOIN USUARIO u ON u.ID_USUARIO = p.ID_USUARIO
JOIN EJEMPLAR e ON e.ID_EJEMPLAR = p.ID_EJEMPLAR
JOIN LIBRO l ON l.ID_LIBRO = e.ID_LIBRO
WHERE p.ESTADO IN ('ACTIVO', 'VENCIDO')
  AND p.FECHA_DEVOLUCION_PREVISTA < TRUNC(CURRENT_DATE);

CREATE OR REPLACE VIEW VW_PRESTAMOS_POR_MES AS
SELECT TO_CHAR(FECHA_PRESTAMO, 'YYYY-MM') AS MES, COUNT(*) AS TOTAL_PRESTAMOS
FROM PRESTAMO
GROUP BY TO_CHAR(FECHA_PRESTAMO, 'YYYY-MM');

CREATE OR REPLACE VIEW VW_PRESTAMOS_POR_USUARIO AS
SELECT u.ID_USUARIO, u.CODIGO, u.NOMBRES || ' ' || u.APELLIDOS AS USUARIO, r.NOMBRE AS ROL,
       COUNT(p.ID_PRESTAMO) AS TOTAL_PRESTAMOS,
       COUNT(CASE WHEN p.ESTADO IN ('ACTIVO', 'VENCIDO') THEN 1 END) AS PRESTAMOS_ABIERTOS,
       COUNT(CASE WHEN p.ESTADO = 'VENCIDO' THEN 1 END) AS PRESTAMOS_VENCIDOS
FROM USUARIO u
JOIN ROL r ON r.ID_ROL = u.ID_ROL
LEFT JOIN PRESTAMO p ON p.ID_USUARIO = u.ID_USUARIO
GROUP BY u.ID_USUARIO, u.CODIGO, u.NOMBRES, u.APELLIDOS, r.NOMBRE;

CREATE OR REPLACE VIEW VW_INVENTARIO_POR_CATEGORIA AS
SELECT c.ID_CATEGORIA, c.NOMBRE AS CATEGORIA,
       COUNT(DISTINCT l.ID_LIBRO) AS TOTAL_LIBROS,
       COUNT(e.ID_EJEMPLAR) AS TOTAL_EJEMPLARES,
       COUNT(CASE WHEN e.ESTADO = 'DISPONIBLE' THEN 1 END) AS DISPONIBLES,
       COUNT(CASE WHEN e.ESTADO = 'PRESTADO' THEN 1 END) AS PRESTADOS,
       COUNT(CASE WHEN e.ESTADO IN ('DANADO', 'PERDIDO', 'INACTIVO') THEN 1 END) AS FUERA_DE_SERVICIO
FROM CATEGORIA c
LEFT JOIN LIBRO l ON l.ID_CATEGORIA = c.ID_CATEGORIA
LEFT JOIN EJEMPLAR e ON e.ID_LIBRO = l.ID_LIBRO
GROUP BY c.ID_CATEGORIA, c.NOMBRE;

CREATE OR REPLACE VIEW VW_DEVOLUCIONES_A_TIEMPO_VS_TARDE AS
SELECT CASE A_TIEMPO WHEN 'S' THEN 'A tiempo' ELSE 'Con retraso' END AS RESULTADO,
       COUNT(*) AS TOTAL,
       ROUND(AVG(DIAS_RETRASO), 1) AS PROMEDIO_DIAS_RETRASO
FROM DEVOLUCION
GROUP BY A_TIEMPO;
