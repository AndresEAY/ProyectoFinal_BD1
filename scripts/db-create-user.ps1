$ErrorActionPreference = "Stop"
. "$PSScriptRoot\env.ps1"
$sql = @"
WHENEVER SQLERROR EXIT FAILURE
SET SERVEROUTPUT ON FEEDBACK OFF
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM dba_users WHERE username = UPPER('$APP_USER');
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE USER $APP_USER IDENTIFIED BY "$APP_USER_PASSWORD" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS';
    DBMS_OUTPUT.PUT_LINE('Usuario $APP_USER creado.');
  ELSE
    DBMS_OUTPUT.PUT_LINE('Usuario $APP_USER ya existe.');
  END IF;
  EXECUTE IMMEDIATE 'GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE, CREATE TRIGGER TO $APP_USER';
END;
/
EXIT
"@
$sql | docker exec -i $DB_CONTAINER sqlplus -s -L $SysConn
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
